/**
 * Firmware key index (0..59, split_heart-layouts.dtsi) -> Figma key name.
 * Rows 0-3 are 12 wide; 48-51 sit under the inner columns; 52-59 are the thumb clusters.
 * Thumbs (confirmed by the owner): 52→50, 53→51, 54→52, 55→53; the right side mirrors it (56→58, 57→59, 58→510, 59→511).
 */
const FIGMA_FOR_INDEX: string[] = [
  ...[0, 1, 2, 3].flatMap(r => Array.from({ length: 12 }, (_, c) => `${r}${c}`)),
  "42", "43", "48", "49",
  "50", "51", "52", "53",
  "58", "59", "510", "511",
];

export const SPLIT_HEART_KEY_COUNT = FIGMA_FOR_INDEX.length;

/** The design's name for a firmware key index, e.g. "00" or "511". */
export const positionName = (i: number) => FIGMA_FOR_INDEX[i] ?? String(i);
/** Which half a firmware key index belongs to. Thumbs and bottom row split at their midpoint. */
export const isLeftKey = (i: number) => i < 48 ? i % 12 < 6 : i < 50 || (i >= 52 && i < 56);

/** SVG transform for firmware key index i (50 x 50 key drawn at its origin). */
export function keyTransform(i: number): string {
  const [a, b, c, d, tx, ty] = FIGMA_KEYS[FIGMA_FOR_INDEX[i]];
  return `matrix(${a} ${c} ${b} ${d} ${tx} ${ty})`;
}

